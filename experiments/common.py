"""Paths and helpers shared by the experiment scripts.

Each experiment has two steps:

    compute()  the simulation; saves raw arrays to results/raw/<name>.npz
               (minutes; run on a compute server: run_all.py --compute)
    plot()     reads the raw arrays, draws the figure and writes the numbers
               to results/<name>.{json,tex} (seconds; run_all.py --plot)

so every figure and every number on a slide is regenerated from saved output.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_v, "1")

import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

FIG = ROOT / "figures"
RES = ROOT / "results"
RAW = RES / "raw"
RAW.mkdir(parents=True, exist_ok=True)


def save_raw(name: str, **arrays):
    np.savez_compressed(RAW / f"{name}.npz", **{k: np.asarray(v) for k, v in arrays.items()})


def load_raw(name: str) -> dict:
    with np.load(RAW / f"{name}.npz") as d:
        return {k: d[k] for k in d.files}


def write_numbers(name: str, numbers: dict):
    """Store results as JSON and as LaTeX macros (letters-only names) for the slides."""
    (RES / f"{name}.json").write_text(json.dumps(numbers, indent=2))
    lines = [f"% generated by experiments/{name}.py; do not edit"]
    for key, val in numbers.items():
        if not key.isalpha():
            raise ValueError(f"macro name must be letters only: {key}")
        lines.append(f"\\newcommand{{\\{key}}}{{{val}}}")
    (RES / f"{name}.tex").write_text("\n".join(lines) + "\n")


def fmt(x, nd=3):
    return f"{x:.{nd}f}"


def fmt_pm(x, se, nd=3):
    return f"{x:.{nd}f} \\pm {se:.{nd}f}"


def fmt_int(n):
    return f"{int(n):,}".replace(",", "{,}")


def pct(x, nd=1):
    return f"{100 * x:.{nd}f}"


def run(compute, plot):
    """Command line for one experiment: --compute, --plot, or both (default)."""
    args = set(sys.argv[1:])
    if not args or "--compute" in args:
        compute()
    if not args or "--plot" in args:
        plot()
